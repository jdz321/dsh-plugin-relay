/** Compact token count: 134000 → "134k", 122000000 → "1.22亿"-style is zh-only; keep k/M universal. */
export function tokenCountText(n: number): string {
  if (!Number.isFinite(n)) return '0'
  if (Math.abs(n) >= 1_000_000_000) return `${trimTrailingZeros(n / 1_000_000_000)}B`
  if (Math.abs(n) >= 1_000_000) return `${trimTrailingZeros(n / 1_000_000)}M`
  if (Math.abs(n) >= 1_000) return `${trimTrailingZeros(n / 1_000)}k`
  return String(n)
}

function trimTrailingZeros(n: number): string {
  return String(Number(n.toFixed(2)))
}

