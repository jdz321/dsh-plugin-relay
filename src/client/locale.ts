/**
 * Compact token count, 1024-based like the `128K = 131072` shorthand:
 * 1048576 → "1M", 131072 → "128k", 45000 → "43.95k".
 */
export function tokenCountText(n: number): string {
  if (!Number.isFinite(n)) return '0'
  if (Math.abs(n) >= 1024 ** 3) return `${trimTrailingZeros(n / 1024 ** 3)}G`
  if (Math.abs(n) >= 1024 ** 2) return `${trimTrailingZeros(n / 1024 ** 2)}M`
  if (Math.abs(n) >= 1024) return `${trimTrailingZeros(n / 1024)}k`
  return String(n)
}

function trimTrailingZeros(n: number): string {
  return String(Number(n.toFixed(2)))
}

